// Writes the site's copy into prototype-mobile/assets/content.js, so the phone
// prototype shows the real words. Offline tooling: `npx tsx scripts/design/dump-content.ts`.
import { writeFileSync } from 'node:fs';
import { journeyChapters } from '../../content/chapters';
import { entourageGroups } from '../../content/entourage';
import { faqEntries } from '../../content/faq';
import { motifGroups } from '../../content/motif';
import { terminalCopy } from '../../content/terminal';
import { verses } from '../../content/verses';
import { daySchedule, timelineIntroLines, venueAddressLines } from '../../content/wedding';
import { sceneAssets } from '../../config/scene-layers.generated';
import { siteConfig } from '../../config/site';

const content = {
  siteConfig,
  terminalCopy,
  verses,
  journeyChapters,
  photos: sceneAssets.chapters,
  daySchedule,
  timelineIntroLines,
  venueAddressLines,
  motifGroups,
  entourageGroups,
  faqEntries,
};
writeFileSync(
  'prototype-mobile/assets/content.js',
  `// generated by scripts/design/dump-content.ts from content/ and config/\nwindow.CONTENT = ${JSON.stringify(content, null, 1)};\n`,
);
console.log('wrote prototype-mobile/assets/content.js');

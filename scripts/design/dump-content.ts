// Writes the site's copy into prototype-mobile/assets/content.js, so the phone
// prototype shows the real words. Offline tooling: `npx tsx scripts/design/dump-content.ts`.
import { writeFileSync } from 'node:fs';
import { phoneContent } from '../../lib/phone/content';

writeFileSync(
  'prototype-mobile/assets/content.js',
  `// generated by scripts/design/dump-content.ts from content/ and config/\nwindow.CONTENT = ${JSON.stringify(phoneContent(), null, 1)};\n`,
);
console.log('wrote prototype-mobile/assets/content.js');

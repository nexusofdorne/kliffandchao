"""Turn the couple's journey photos and films into web files, and list them for the site.

    python scripts/design/prepare_journey_media.py [SOURCE]

SOURCE (default: 3.0/elements/03 - photos) holds one folder per chapter, named so they
sort in order ("01_It started with a wedding", ...). In each folder the files are
numbered in the order they appear: "0 - Video.mp4" first (optional), then 1, 2, 3...
photos (jpg, png or HEIC). Writes
  public/img/journey/ch<N>_<K>.jpg        (long side at most 1200 px, EXIF rotation applied)
  public/video/journey/ch<N>.mp4          (960 px tall, muted, H.264; needs ffmpeg on PATH or WinGet)
  config/journey-media.generated.ts       (each chapter's film and photos, with pixel sizes)
Offline tooling: Python 3 with Pillow and pillow-heif. Re-run it after changing the photos.
"""
import json
import os
import re
import shutil
import subprocess
import sys

from PIL import Image, ImageOps
from pillow_heif import register_heif_opener

register_heif_opener()

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "3.0", "elements", "03 - photos")
IMG_OUT = os.path.join(REPO, "public", "img", "journey")
VID_OUT = os.path.join(REPO, "public", "video", "journey")
LONG_SIDE = 1200
PHOTO_EXT = (".jpg", ".jpeg", ".png", ".heic")


def ffmpeg():
    found = shutil.which("ffmpeg")
    if found:
        return found
    winget = os.path.expandvars(r"%LOCALAPPDATA%\Microsoft\WinGet\Links\ffmpeg.exe")
    if os.path.exists(winget):
        return winget
    sys.exit("ffmpeg not found")


def number(name):
    m = re.match(r"\s*(\d+)", name)
    return int(m.group(1)) if m else 10**6


def encode_film(src, dst):
    if os.path.exists(dst) and os.path.getmtime(dst) > os.path.getmtime(src):
        return
    subprocess.run([ffmpeg(), "-v", "error", "-y", "-i", src, "-vf", "scale=-2:960,fps=30",
                    "-c:v", "libx264", "-preset", "slow", "-crf", "27", "-profile:v", "high",
                    "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", dst], check=True)


def main():
    os.makedirs(IMG_OUT, exist_ok=True)
    os.makedirs(VID_OUT, exist_ok=True)
    chapters = sorted((d for d in os.listdir(SOURCE) if os.path.isdir(os.path.join(SOURCE, d))), key=number)
    manifest = []
    for n, folder in enumerate(chapters, 1):
        path = os.path.join(SOURCE, folder)
        files = sorted(os.listdir(path), key=number)
        entry = {"film": None, "photos": []}
        for name in files:
            src = os.path.join(path, name)
            ext = os.path.splitext(name)[1].lower()
            if ext == ".mp4":
                dst = os.path.join(VID_OUT, f"ch{n}.mp4")
                encode_film(src, dst)
                w, h = probe_size(dst)
                entry["film"] = {"src": f"/video/journey/ch{n}.mp4", "px": [w, h]}
            elif ext in PHOTO_EXT:
                k = len(entry["photos"]) + 1
                im = ImageOps.exif_transpose(Image.open(src)).convert("RGB")
                im.thumbnail((LONG_SIDE, LONG_SIDE), Image.Resampling.LANCZOS)
                out = f"ch{n}_{k}.jpg"
                im.save(os.path.join(IMG_OUT, out), quality=84, optimize=True, progressive=True)
                entry["photos"].append({"src": f"/img/journey/{out}", "px": [im.width, im.height]})
        print(f"chapter {n}: {folder}: film={'yes' if entry['film'] else 'no'}, {len(entry['photos'])} photos")
        manifest.append(entry)
    out_ts = os.path.join(REPO, "config", "journey-media.generated.ts")
    with open(out_ts, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by scripts/design/prepare_journey_media.py; do not edit by hand.\n"
                "// One entry per journey chapter, in order: its film (or null) and its photos, in order.\n"
                "import type { JourneyMedia } from '@/lib/journey/gallery';\n\n"
                "export const journeyMedia = ")
        json.dump(manifest, f, indent=2)
        f.write(" as const satisfies readonly JourneyMedia[];\n")
    print("wrote", out_ts)


def probe_size(video):
    probe = ffmpeg().replace("ffmpeg", "ffprobe")
    out = subprocess.run([probe, "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height",
                          "-of", "csv=p=0", video], check=True, capture_output=True, text=True).stdout
    w, h = out.strip().split(",")
    return int(w), int(h)


if __name__ == "__main__":
    main()

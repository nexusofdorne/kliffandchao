// Copies the phone design (prototype-mobile/) into public/m/, where the site serves it to
// phones. The page keeps only the public words (assets/public-content.js); everything else
// comes from /api/phone-content after the password. Run after changing the prototype:
// `npx tsx scripts/design/publish-phone.ts`.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename } from 'node:path';
import { phonePublicContent } from '../../lib/phone/content';
import { buildWorldGL } from './build-world-gl';
import { siteConfig } from '../../config/site';

const SRC = 'prototype-mobile';
const OUT = 'public/m';

buildWorldGL();
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const file of ['app.js', 'styles.css']) cpSync(`${SRC}/${file}`, `${OUT}/${file}`);
cpSync(`${SRC}/assets`, `${OUT}/assets`, {
  recursive: true,
  filter: (path) => basename(path) !== 'content.js',
});
writeFileSync(
  `${OUT}/assets/public-content.js`,
  `// generated by scripts/design/publish-phone.ts\nwindow.PUBLIC_CONTENT = ${JSON.stringify(phonePublicContent())};\n`,
);

let html = readFileSync(`${SRC}/index.html`, 'utf8');
const swap = (from: string, to: string) => {
  if (!html.includes(from)) throw new Error(`publish-phone: "${from}" not found in index.html`);
  html = html.replace(from, to);
};
swap('<script src="assets/content.js"></script>', '<script src="assets/public-content.js"></script>');
swap(
  '<title>Kliff &amp; Chao (phone prototype)</title>',
  `<title>${siteConfig.coupleNames.replace('&', '&amp;')} — ${siteConfig.weddingDateDisplay}</title>\n  <meta name="robots" content="noindex, nofollow">`,
);
// the prototype's server maps site/ to public/; on the site those files are at the root
html = html.replaceAll('"site/', '"/');
writeFileSync(`${OUT}/index.html`, html);
console.log(`published ${SRC} -> ${OUT}`);

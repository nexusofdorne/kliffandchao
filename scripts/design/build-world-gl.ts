// Bundles lib/world-gl for the phone design: prototype-mobile/assets/world-gl.js, a plain
// script that sets window.WorldGL. publish-phone.ts runs it first, so public/m gets it too.
// `npx tsx scripts/design/build-world-gl.ts` to build it on its own (the prototype's server
// serves prototype-mobile/ as it is).
import { buildSync } from 'esbuild';

export function buildWorldGL() {
  buildSync({
    entryPoints: ['lib/world-gl/browser.ts'],
    bundle: true,
    format: 'iife',
    globalName: 'WorldGL',
    target: 'es2019',
    minify: true,
    legalComments: 'none',
    banner: { js: '// generated by scripts/design/build-world-gl.ts from lib/world-gl; do not edit' },
    outfile: 'prototype-mobile/assets/world-gl.js',
  });
}

if (process.argv[1]?.includes('build-world-gl')) {
  buildWorldGL();
  console.log('wrote prototype-mobile/assets/world-gl.js');
}
